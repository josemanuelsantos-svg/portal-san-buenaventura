export function getSupportForSession(dayIdx, periodId, aula, currentTeacherId = null) {
  if (!aula) return [];
  const dStr = String(dayIdx);
  return SCHOOL_SUPPORT_ASSIGNMENTS.filter(item => {
    if (String(item.day) !== dStr || item.period !== periodId) return false;
    const matchesAula = item.aulas.some(a => a === aula || aula.includes(a));
    if (!matchesAula) return false;
    if (currentTeacherId && item.teacherId === currentTeacherId) return false;
    return true;
  });
}

export function formatSupportText(list) {
  if (!list || list.length === 0) return "";
  return list.map(s => {
    const displayName = (s.teacherId === "ipena" || s.teacherId === "feli")
      ? "Feli"
      : s.teacherName;
    return `${displayName}${s.note ? ` (${s.note})` : ""}`;
  }).join(" · ");
}


